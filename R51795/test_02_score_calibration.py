class TestCalibrationByDecile(unittest.TestCase):

    def test_calibration_has_ten_deciles(self):
        """calibration_by_decile must contain exactly 10 entries."""
        n_deciles = len(_actual["calibration_by_decile"])
        self.assertEqual(
            n_deciles,
            10,
            f"Expected 10 deciles, got {n_deciles} – use q=10 in pd.qcut()",
        )

    def test_calibration_values_are_churn_rates(self):
        """Every decile churn rate must be in [0, 1]."""
        for decile, rate in _actual["calibration_by_decile"].items():
            self.assertGreaterEqual(rate, 0.0, f"Decile {decile} rate < 0")
            self.assertLessEqual(rate, 1.0, f"Decile {decile} rate > 1")

    def test_calibration_values_match_reference(self):
        """Decile churn rates must match the reference implementation (±1e-6)."""
        expected_calib = _expected["calibration_by_decile"]
        actual_calib = _actual["calibration_by_decile"]
        for decile in expected_calib:
            self.assertIn(decile, actual_calib, f"Decile {decile} missing")
            self.assertAlmostEqual(
                actual_calib[decile],
                expected_calib[decile],
                places=6,
                msg=f"Decile {decile} rate incorrect – use .mean() aggregation",
            )


