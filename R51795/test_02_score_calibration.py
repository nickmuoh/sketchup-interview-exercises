# ---------------------------------------------------------------------------
# Reference implementation (answer key)
# ---------------------------------------------------------------------------
def _reference_calibrate_and_lift(scores_df: pd.DataFrame, labels_df: pd.DataFrame) -> dict:
    """Canonical implementation derived from the answer key."""
    # 1. Merge – inner join
    df = scores_df.merge(labels_df, on=["account_id", "predict_period_end"], how="inner")

    # 2. Bin into 10 deciles
    df["decile"] = pd.qcut(df["score"], q=10, labels=False, duplicates="drop")

    # 3. Aggregation – mean for calibration and baseline
    calib = df.groupby("decile")["churn_label"].mean()
    baseline = df["churn_label"].mean()

    # 4. Top decile – highest decile label
    top_decile_rate = calib.loc[df["decile"].max()]

    # 5. Lift
    lift = top_decile_rate / baseline

    # 6. Capture – top 10 % most risky
    df_sorted = df.sort_values("score", ascending=False)
    total_churns = df["churn_label"].sum()
    capture_top10 = (
        df_sorted.head(int(len(df_sorted) * 0.10))["churn_label"].sum() / total_churns
    )

    # 7. Tiers – thresholds 0.3 / 0.6
    tiers = pd.cut(
        df["score"], bins=[0.0, 0.3, 0.6, 1.0], labels=["low", "medium", "high"]
    )

    return {
        "baseline_rate": float(baseline),
        "top_decile_rate": float(top_decile_rate),
        "lift": float(lift),
        "capture_top10": float(capture_top10),
        "calibration_by_decile": calib.to_dict(),
        "tiers_example_counts": tiers.value_counts().to_dict(),
    }


